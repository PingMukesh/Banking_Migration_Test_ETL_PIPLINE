-- Clean up existing tables if present (optional)
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'FACT_TRANSACTIONS', 'FACT_LOAN_PORTFOLIO', 'DAILY_BALANCE_SUMMARY',
        'ETL_REJECTED_RECORDS', 'DIM_ACCOUNT', 'DIM_CUSTOMER', 'DIM_BRANCH'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
    END LOOP;
END;
/

-- 1. DIM_BRANCH
CREATE TABLE DIM_BRANCH (
    BRANCH_SK           NUMBER(10,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    BRANCH_CODE         VARCHAR2(10) NOT NULL UNIQUE,
    BRANCH_NAME         VARCHAR2(100) NOT NULL,
    REGION              VARCHAR2(50) NOT NULL,
    POSTAL_CODE         VARCHAR2(20),
    SWIFT_BIC           VARCHAR2(11) DEFAULT 'OCIBUS33XXX',
    CREATED_TIMESTAMP   TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL
);

-- 2. DIM_CUSTOMER
CREATE TABLE DIM_CUSTOMER (
    CUSTOMER_SK         NUMBER(12,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID         NUMBER(10,0) NOT NULL,
    FULL_NAME           VARCHAR2(120) NOT NULL,
    MASKED_TAX_ID       VARCHAR2(25) NOT NULL,
    EMAIL               VARCHAR2(100),
    PHONE_STANDARDIZED  VARCHAR2(30),
    STATUS              VARCHAR2(20) NOT NULL CHECK (STATUS IN ('ACTIVE', 'INACTIVE', 'SUSPENDED', 'DECEASED')),
    KYC_STATUS          VARCHAR2(20) NOT NULL CHECK (KYC_STATUS IN ('VERIFIED', 'PENDING')),
    CREDIT_SCORE        NUMBER(4,0),
    DATE_OF_BIRTH       DATE,
    CITY                VARCHAR2(50),
    STATE_PROV          VARCHAR2(50),
    START_DATE          DATE NOT NULL,
    END_DATE            DATE,
    IS_CURRENT          VARCHAR2(1) DEFAULT 'Y' NOT NULL CHECK (IS_CURRENT IN ('Y', 'N')),
    DW_INSERT_DATE      TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL
);

-- 3. DIM_ACCOUNT
CREATE TABLE DIM_ACCOUNT (
    ACCOUNT_SK          NUMBER(12,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACCOUNT_NUMBER      VARCHAR2(20) NOT NULL UNIQUE,
    CUSTOMER_SK         NUMBER(12,0) NOT NULL,
    BRANCH_SK           NUMBER(10,0) NOT NULL,
    ACCOUNT_TYPE        VARCHAR2(30) NOT NULL CHECK (ACCOUNT_TYPE IN ('SAVINGS', 'CHECKING', 'MONEY_MARKET', 'LOAN', 'CERTIFICATE_OF_DEPOSIT')),
    CURRENCY_CODE       VARCHAR2(3) DEFAULT 'USD' NOT NULL,
    CURRENT_BALANCE     NUMBER(18,2) NOT NULL,
    INTEREST_RATE       NUMBER(5,2) NOT NULL,
    STATUS              VARCHAR2(20) NOT NULL CHECK (STATUS IN ('ACTIVE', 'CLOSED', 'DORMANT')),
    OPEN_DATE           DATE NOT NULL,
    OVERDRAFT_LIMIT     NUMBER(18,2) DEFAULT 0.00 NOT NULL,
    DW_INSERT_DATE      TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_ACCT_CUST FOREIGN KEY (CUSTOMER_SK) REFERENCES DIM_CUSTOMER (CUSTOMER_SK),
    CONSTRAINT FK_ACCT_BRANCH FOREIGN KEY (BRANCH_SK) REFERENCES DIM_BRANCH (BRANCH_SK)
);

-- 4. FACT_TRANSACTIONS
CREATE TABLE FACT_TRANSACTIONS (
    TXN_SK              NUMBER(18,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TXN_ID              VARCHAR2(30) NOT NULL UNIQUE,
    ACCOUNT_SK          NUMBER(12,0) NOT NULL,
    TXN_TIMESTAMP       TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    TXN_TYPE            VARCHAR2(10) NOT NULL CHECK (TXN_TYPE IN ('DEBIT', 'CREDIT')),
    CHANNEL             VARCHAR2(20) NOT NULL,
    AMOUNT              NUMBER(18,2) NOT NULL,
    BALANCE_AFTER_TXN   NUMBER(18,2) NOT NULL,
    AML_FLAG            VARCHAR2(1) DEFAULT 'N' NOT NULL CHECK (AML_FLAG IN ('Y', 'N')),
    TXN_STATUS          VARCHAR2(20) DEFAULT 'SUCCESS' NOT NULL,
    DW_INSERT_DATE      TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_TXN_ACCT FOREIGN KEY (ACCOUNT_SK) REFERENCES DIM_ACCOUNT (ACCOUNT_SK)
);

-- 5. FACT_LOAN_PORTFOLIO
CREATE TABLE FACT_LOAN_PORTFOLIO (
    LOAN_SK             NUMBER(12,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    LOAN_ID             VARCHAR2(20) NOT NULL UNIQUE,
    ACCOUNT_SK          NUMBER(12,0) NOT NULL,
    CUSTOMER_SK         NUMBER(12,0) NOT NULL,
    LOAN_PRODUCT        VARCHAR2(50) NOT NULL,
    PRINCIPAL_AMOUNT    NUMBER(18,2) NOT NULL,
    OUTSTANDING_BALANCE NUMBER(18,2) NOT NULL,
    INTEREST_RATE       NUMBER(5,2) NOT NULL,
    MONTHLY_EMI         NUMBER(18,2) NOT NULL,
    TENURE_MONTHS       NUMBER(5,0) NOT NULL,
    DISBURSEMENT_DATE   DATE NOT NULL,
    DELINQUENCY_STATUS  VARCHAR2(30) NOT NULL,
    DW_INSERT_DATE      TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_LOAN_ACCT FOREIGN KEY (ACCOUNT_SK) REFERENCES DIM_ACCOUNT (ACCOUNT_SK),
    CONSTRAINT FK_LOAN_CUST FOREIGN KEY (CUSTOMER_SK) REFERENCES DIM_CUSTOMER (CUSTOMER_SK)
);

-- 6. DAILY_BALANCE_SUMMARY
CREATE TABLE DAILY_BALANCE_SUMMARY (
    SUMMARY_SK              NUMBER(12,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SNAPSHOT_DATE           DATE NOT NULL,
    ACCOUNT_SK              NUMBER(12,0) NOT NULL,
    OPENING_BALANCE         NUMBER(18,2) NOT NULL,
    TOTAL_DEBIT_AMOUNT      NUMBER(18,2) DEFAULT 0.00 NOT NULL,
    TOTAL_CREDIT_AMOUNT     NUMBER(18,2) DEFAULT 0.00 NOT NULL,
    CLOSING_BALANCE         NUMBER(18,2) NOT NULL,
    TOTAL_TXN_COUNT         NUMBER(10,0) DEFAULT 0 NOT NULL,
    RECONCILIATION_STATUS   VARCHAR2(20) DEFAULT 'BALANCED' NOT NULL CHECK (RECONCILIATION_STATUS IN ('BALANCED', 'DISCREPANCY')),
    DW_INSERT_DATE          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT FK_BAL_ACCT FOREIGN KEY (ACCOUNT_SK) REFERENCES DIM_ACCOUNT (ACCOUNT_SK)
);

-- 7. ETL_REJECTED_RECORDS
CREATE TABLE ETL_REJECTED_RECORDS (
    REJECT_ID               NUMBER(12,0) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SOURCE_TABLE            VARCHAR2(50) NOT NULL,
    SOURCE_RECORD_KEY       VARCHAR2(50) NOT NULL,
    REJECT_REASON           VARCHAR2(255) NOT NULL,
    RAW_RECORD_PAYLOAD      VARCHAR2(1000) NOT NULL,
    QUARANTINE_TIMESTAMP    TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL
);

